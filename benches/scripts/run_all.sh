#!/usr/bin/env bash
# Orchestrator. Everything runs through here so there is exactly one place
# that knows the order of operations.
#
# Arguments:
#   $1         timestamp (YYYYMMDDTHHMMSSZ) — used to name the results dir
#   --only X   run only one of: python | node | rust (default: all three)
#
# Contract:
#   - Writes machine fingerprint to $RESULTS/env.json
#   - Writes each variant's raw output to $RESULTS/{python,node,rust}/<name>.json
#   - Invokes scripts/report.py at the end
#
# Exit codes:
#   0  all good
#   1  a benchmark failed (partial results are still written)
#   2  missing prerequisites

set -euo pipefail

STAMP="${1:?usage: run_all.sh <stamp> [--only python|node|rust]}"
shift || true

ONLY=""
if [[ "${1:-}" == "--only" ]]; then
    ONLY="${2:?--only needs a value}"
fi

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BENCH_ROOT="$(dirname "$HERE")"
RESULTS="$BENCH_ROOT/results/$STAMP"
PYTHON_BIN="${FURY_BENCH_PYTHON:-python3}"
FAILURES=0

# ── prerequisites ────────────────────────────────────────────────────────
if [[ "$ONLY" != "rust" ]]; then
    "$PYTHON_BIN" -c 'import fury, orjson, msgpack, asyncpg' 2>/dev/null || {
        echo "ERROR: Python module 'fury' not importable." >&2
        echo "       From repo root: python -m venv .venv && source .venv/bin/activate && (cd fury-py && maturin develop --release)" >&2
        exit 2
    }
fi
if [[ "$ONLY" == "" || "$ONLY" == "node" ]]; then
    command -v node >/dev/null || { echo "ERROR: node not found" >&2; exit 2; }
    export FURY_BENCH_WASM="${FURY_BENCH_WASM:-$BENCH_ROOT/../fury-ts/pkg/fury_ts.js}"
    if [[ ! -f "$FURY_BENCH_WASM" ]]; then
        echo "ERROR: FURY_BENCH_WASM must point to Node-target fury_ts.js." >&2
        exit 2
    fi
fi

mkdir -p "$RESULTS"/{python,node,rust,rust-raw}

# ── environment ──────────────────────────────────────────────────────────
bash "$HERE/env.sh" > "$RESULTS/env.json"
echo "→ env captured: $RESULTS/env.json"

# ── fixtures ─────────────────────────────────────────────────────────────
# The Node benchmark reads pre-generated byte fixtures. We generate them from
# the Python side so the payloads are exactly what the server would produce.
if [[ "$ONLY" == "" || "$ONLY" == "node" ]]; then
    echo "→ generating fixtures"
    (cd "$BENCH_ROOT/python" && "$PYTHON_BIN" -m run --emit-fixtures --fixture-dir "$RESULTS/fixtures")
fi

# ── python ───────────────────────────────────────────────────────────────
if [[ "$ONLY" == "" || "$ONLY" == "python" ]]; then
    echo "→ python benchmarks"
    for v in \
        asyncpg_to_dicts \
        asyncpg_to_json_stdlib \
        asyncpg_to_json_orjson \
        asyncpg_to_msgpack \
        fury_to_models \
        fury_to_bytes \
        fury_to_models_read3
    do
        echo "   · $v"
        (cd "$BENCH_ROOT/python" && \
            "$PYTHON_BIN" -m run --variant "$v" --out "$RESULTS/python/$v.json") \
            || { echo "     (failed, continuing)" >&2; FAILURES=$((FAILURES + 1)); }
    done
fi

# ── node ─────────────────────────────────────────────────────────────────
if [[ "$ONLY" == "" || "$ONLY" == "node" ]]; then
    echo "→ node benchmarks"
    npm ci --prefix "$BENCH_ROOT/node" --ignore-scripts --no-audit --no-fund
    for v in \
        json_parse_only \
        json_parse_read3 \
        json_update_roundtrip \
        msgpack_decode_only \
        msgpack_decode_read3 \
        msgpack_update_roundtrip \
        fury_construct_only \
        fury_construct_read3 \
        fury_update_roundtrip
    do
        echo "   · $v"
        (cd "$BENCH_ROOT/node" && \
            node --expose-gc run.mjs --variant "$v" --out "$RESULTS/node/$v.json" --fixtures "$RESULTS/fixtures") \
            || { echo "     (failed, continuing)" >&2; FAILURES=$((FAILURES + 1)); }
    done
fi

# ── rust ─────────────────────────────────────────────────────────────────
if [[ "$ONLY" == "" || "$ONLY" == "rust" ]]; then
    echo "→ rust benchmarks (criterion)"
    (cd "$BENCH_ROOT/rust" && \
        CARGO_TARGET_DIR=./target cargo bench --locked --quiet -- --output-format bencher) \
        | tee "$RESULTS/rust/criterion.txt"

    # Criterion honors CARGO_TARGET_DIR, not cargo's --target-dir flag.
    # Depending on whether benches/rust is a workspace member, the directory
    # can land in one of two places. Search both, don't fail if neither exists.
    CRIT_DIR=""
    for cand in "$BENCH_ROOT/rust/target/criterion" "$BENCH_ROOT/../target/criterion"; do
        if [[ -d "$cand" ]]; then
            CRIT_DIR="$cand"
            break
        fi
    done

    if [[ -n "$CRIT_DIR" ]]; then
        echo "   estimates from: $CRIT_DIR"
        find "$CRIT_DIR" -name estimates.json -path '*/new/*' 2>/dev/null \
            -exec bash -c '
                src="$1"
                rel="${src#*/criterion/}"
                dst="'"$RESULTS"'/rust-raw/${rel%/estimates.json}.json"
                mkdir -p "$(dirname "$dst")"
                cp "$src" "$dst"
            ' _ {} \;
    else
        echo "   ! criterion estimates not found; rust-raw will be empty"
    fi
fi

# ── report ───────────────────────────────────────────────────────────────
python3 "$HERE/report.py" "$RESULTS"
if (( FAILURES > 0 )); then
    echo "$FAILURES benchmark variant(s) failed" >&2
    exit 1
fi
